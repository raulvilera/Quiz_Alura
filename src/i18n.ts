type Category = Question["category"];

/** Alunos que fazem o quiz somente em russo (nome comparado sem acentos e em maiúsculas). */
export function isRussianStudent(name: string): boolean {
  const n = name.normalize("NFD").replace(/[̀-ͯ]/g, "").toUpperCase();
  return n.includes("ZLATA") && n.includes("SAFOROVA");
}

export function localizeQuestion(question: Question, lang: Lang): Question {
  if (lang !== "ru") return question;
  const ru = questionsRu[question.id];
  if (!ru) return question;
  return {
    ...question,
    prompt: ru.prompt,
    options: ru.options ?? question.options,
    explanation: ru.explanation,
    expected: ru.expected ?? question.expected,
  };
}

